/* Real-user monitoring: report Experienced Page Time for this page view.

   WHAT THIS MEASURES, AND WHY IT HAS TO HAPPEN HERE
   Experienced Page Time is "how long until the page is in a state a person can
   click". The server cannot know that: it finishes writing the response and has
   no idea whether the browser has parsed the HTML, run the deferred scripts, or
   is still waiting on a web font. Only the browser knows, and the Navigation
   Timing API is the only place it is recorded. So the measurement is taken here
   and the server is told the result.

   WHERE THE PAGE TYPE COMES FROM
   ExperienceFilter labels the request and header.jspf renders it into the page as
   window.__EPT_PT. It is not read from a response header, because the Navigation
   Timing API does not expose response headers -- a header-based version of this
   script would look correct and silently report nothing.

   WHAT IS SENT, AND WHY THE SPLIT MATTERS
     i   interactive: domInteractive from navigation start. The headline EPT.
     d   DOMContentLoaded from navigation start.
     l   load from navigation start (images, fonts, everything).
     b   ttfb: responseStart from navigation start -- everything before the first
         byte, so connection setup and TLS are inside it.
     s   server think time: responseStart - requestStart, which excludes the
         connection and upload and is the part an operator can actually change.
     t   transferSize: encoded bytes for the document.

   b and s are the difference between "the server took too long" and "the
   connection cost too much". A single combined figure could not tell an operator
   which of the two to go and fix, so they are reported separately rather than
   averaged into one number that means neither.

   The server's own in-container timing is NOT sent from here. It cannot be: it is
   not known until the response has been written, so there is nowhere left to put
   it that this script could read. That measurement lives in MetricsCollector
   instead, and the two are labelled as distinct rather than merged.

   WHERE THE BEACON GOES
   ExperienceBeaconServlet at /realtime/ept, as a GET. GET is not an accident: it
   is the one endpoint taking untrusted input into a table, and a POST would force
   an exemption from CSRFProtectionFilter that would be a real weakening. Both
   rate limiters already skip GET.

   SAMPLING IS NOT DONE HERE
   The server decides which 1-in-N views to keep, from its own configuration, so
   the rate shown on /admin/performance is a property of the deployment. That does
   mean this script sends a small GET for every page view and the server discards
   most of them; sampling here would halve that traffic but would make the volume
   figures depend on client behaviour, and a wrong volume is worse than a wasted
   request.

   SILENT BY DESIGN
   Nothing here may delay or disturb a shopper. Every failure -- no Timing API, an
   unsupported browser, a blocked request, a beacon that never arrives -- results in
   no report and nothing visible. The worst outcome is a missing sample, never a
   broken page. */
(function () {
    'use strict';

    if (!window.performance || typeof window.performance.getEntriesByType !== 'function') {
        return; // no Navigation Timing API: nothing honest to report
    }

    var CTX = window.CTXPATH || '';

    /* Do Not Track. This reports page timings and stores no IP, user id, session
       or full URL -- but a person who asks not to be tracked should not have to
       know that argument in order to be believed. */
    var dnt = navigator.doNotTrack || window.doNotTrack;
    if (dnt === '1' || dnt === 'yes') {
        return;
    }

    /* Absent on anything that is not a page view: static assets, the beacon
       itself, /health, the SSE stream, and 404s, which have no route template. */
    var pageType = window.__EPT_PT;
    if (typeof pageType !== 'string' || !pageType) {
        return;
    }
    /* The value is generated by PageType and never by the browser, so this cannot
       normally fail. It is checked anyway because a route string ends up in a
       database, and an unexpected one should be dropped rather than stored. */
    if (!/^[a-z0-9][a-z0-9/_\-:.]{0,63}$/.test(pageType)) {
        return;
    }

    var entry = null;
    try {
        var entries = window.performance.getEntriesByType('navigation');
        entry = entries && entries.length ? entries[0] : null;
    } catch (e) {
        return;
    }
    if (!entry) {
        return;
    }

    /* An unload in progress or a prerender: these timings do not describe what a
       person experienced, so they are skipped rather than recorded. */
    if (typeof entry.activationStart === 'number' && entry.activationStart > 0) {
        return; // prerendered: this is the time from activation, not a fresh load
    }
    if (document.visibilityState === 'hidden') {
        return;
    }

    /* startTime is 0 for a document navigation, but entries are expressed
       relative to the time origin, so subtracting is correct in both cases
       rather than assuming a zero baseline. */
    var origin = typeof entry.startTime === 'number' ? entry.startTime : 0;

    var interactive = since(entry.domInteractive, origin);
    var domReady = since(entry.domContentLoadedEventEnd, origin);
    var load = since(entry.loadEventEnd, origin);
    var ttfb = since(entry.responseStart, origin);
    var server = since(entry.responseStart, entry.requestStart);

    /* domInteractive is 0 in browsers that do not support it, and a genuine 0 is
       indistinguishable from that. Fall back to DOMContentLoaded rather than
       recording an implausibly fast page. */
    if (interactive <= 0) {
        interactive = domReady;
    }

    if (interactive < 0 && domReady < 0 && load < 0 && ttfb < 0) {
        return; // nothing measurable about this view
    }

    var qs = 'pt=' + encodeURIComponent(pageType)
        + '&i=' + val(interactive)
        + '&d=' + val(domReady)
        + '&l=' + val(load)
        + '&b=' + val(ttfb)
        + '&s=' + val(server)
        + '&t=' + bytes(entry.transferSize);

    /* Sent without waiting for, or being affected by, the result: the report is
       not worth a shopper's bandwidth to acknowledge, and on a navigation the
       request would likely be cancelled anyway. keepalive is what survives that
       cancellation. */
    try {
        if (typeof window.fetch === 'function') {
            window.fetch(CTX + '/realtime/ept?' + qs, {
                method: 'GET',
                keepalive: true,
                credentials: 'omit'
            })['catch'](noop);
        } else {
            /* No fetch, so an image request: still a GET, still fire-and-forget.
               navigator.sendBeacon is deliberately not used as the fallback --
               it only ever POSTs, which would run into CSRFProtectionFilter and
               be rejected, so it would be a fallback that never works. */
            new Image().src = CTX + '/realtime/ept?' + qs;
        }
    } catch (e) {
        /* Deliberately swallowed: a shopper must never see a performance error. */
    }

    function since(value, from) {
        if (typeof value !== 'number' || value <= 0) {
            return -1;
        }
        if (typeof from !== 'number' || from < 0) {
            from = 0;
        }
        return Math.round(value - from);
    }

    function val(v) {
        return v === null || v === undefined || v < 0 ? -1 : Math.round(v);
    }

    function bytes(v) {
        return typeof v === 'number' && isFinite(v) && v >= 0 ? Math.round(v) : 0;
    }

    function noop() {
    }
})();